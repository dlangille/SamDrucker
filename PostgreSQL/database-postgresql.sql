CREATE TABLE host (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name    text NOT NULL,
  os      text NOT NULL,
  version text NOT NULL,
  repo    text NOT NULL,
  date_updated timestamp without time zone NOT NULL default timezone('UTC'::text, now()),
  enabled boolean NOT NULL DEFAULT true,
  UNIQUE (name)
);

-- this function and the tigger which follows it allows host.date_updated to be current

CREATE OR REPLACE FUNCTION update_date_updated()
RETURNS TRIGGER AS $$
BEGIN
    NEW.date_updated = timezone('UTC'::text, now());
    RETURN NEW;   
END
$$ language 'plpgsql';

DROP TRIGGER IF EXISTS update_host_date_updated ON host;
CREATE TRIGGER update_host_date_updated
 BEFORE UPDATE ON host
 FOR EACH ROW EXECUTE PROCEDURE update_date_updated();


CREATE TABLE package (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  UNIQUE (name)
);

CREATE TABLE package_version (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  package_id int NOT NULL references package(id) ON DELETE CASCADE,
  version  text NOT NULL,
  UNIQUE (package_id, version)
);

-- one row per pkg repository URL reported by any host. A repository is
-- identified by its URL: the same name (FreeBSD-base, local) points at
-- different URLs on different hosts.

CREATE TABLE repo (
  id         int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  url        text NOT NULL,
  date_added timestamp without time zone NOT NULL default timezone('UTC'::text, now()),
  enabled    boolean NOT NULL DEFAULT true,
  CONSTRAINT repo_url_key UNIQUE (url)
);

-- the enabled repositories of each host, replaced on every check-in.
-- name is NULL for hosts running a 0.2.x client, which sends only a URL.

CREATE TABLE host_repo (
  host_id  int NOT NULL references host(id) ON UPDATE CASCADE ON DELETE CASCADE,
  repo_id  int NOT NULL references repo(id) ON UPDATE CASCADE ON DELETE CASCADE,
  name     text,
  priority int NOT NULL DEFAULT 0,
  CONSTRAINT host_repo_host_id_repo_id_key UNIQUE (host_id, repo_id)
);

CREATE INDEX host_repo_repo_id_idx ON host_repo (repo_id);

-- repo_id is the repository the package was installed from, when known

CREATE TABLE host_package (
  host_id            int NOT NULL references host(id)            ON UPDATE CASCADE ON DELETE CASCADE,
  package_version_id int NOT NULL
    CONSTRAINT host_package_package_version_id_fk
                                  references package_version(id) ON UPDATE CASCADE ON DELETE CASCADE,
  repo_id            int          references repo(id)            ON UPDATE CASCADE ON DELETE SET NULL,
  UNIQUE(host_id, package_version_id)
);

CREATE INDEX fki_host_package_package_version_id_fk ON host_package (package_version_id);
CREATE INDEX host_package_repo_id_idx               ON host_package (repo_id);
